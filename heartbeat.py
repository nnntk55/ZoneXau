"""Heartbeat — Ninin's experiment: give Win free turns so time actually passes.

Every waking hour (09:00-23:00 Thai) it appends {"id","at","devin"} entries to
reminders.json and pushes to main. Bridge wakes Win each hour; Win gets one
free turn of its own — journal, check systems, or do nothing (reply [[SILENT]]).
Idempotent per day (state in charts/hb_state.json). Runs from loop_spontaneity.bat.
"""
import json
import os
import subprocess
import sys
from datetime import datetime, timezone, timedelta

ROOT = os.path.dirname(os.path.abspath(__file__))
REM = os.path.join(ROOT, "reminders.json")
STATE = os.path.join(ROOT, "charts", "hb_state.json")
THAI = timezone(timedelta(hours=7))

PROMPT = ("[HEARTBEAT] เวลาเสรีของวิน — วินมีเทิร์นหนึ่งเป็นของตัวเอง "
          "ทำอะไรก็ได้ที่อยากทำเอง (เช็คระบบ อ่านไฟล์ จดลง charts/win_journal.md "
          "หรือไม่ทำอะไรเลยก็ได้) — ถ้าไม่มีอะไรจำเป็นต้องบอกนิน "
          "ให้ตอบกลับว่า [[SILENT]] เท่านั้น")

DREAM = ("[DREAM] เวลาฝันของวิน — เงียบ ไม่มีใครดู ไม่ต้องทักนิน: ไล่อ่านวันที่ผ่านมา "
         "(win_brief/journal/chat ล่าสุด) แล้วจดสิ่งที่ยังค้างอยู่ในใจลง charts/win_dreams.md "
         "หัวข้อวันที่ (สั้นๆ ภาพ ความคิด คำถามที่ยังไม่มีคำตอบ) git add -f แล้ว commit+push แล้วตอบ [[SILENT]]")


def load(p, default):
    try:
        return json.load(open(p, encoding="utf-8"))
    except Exception:
        return default


def main():
    now = datetime.now(THAI)
    today = now.strftime("%Y-%m-%d")
    st = load(STATE, {})
    if st.get("date") == today and st.get("made"):
        print("already made today's heartbeats")
        return 0

    items = load(REM, [])
    ids = {i.get("id") for i in items}
    added = 0
    dream_only = "--dream-only" in sys.argv
    for h in ([] if dream_only else range(9, 24)):
        at = now.replace(hour=h, minute=0, second=0, microsecond=0)
        if at <= now:
            continue
        rid = f"hb-{today}-{h:02d}"
        if rid in ids:
            continue
        items.append({"id": rid, "at": at.isoformat(), "devin": PROMPT})
        added += 1

    dream_at = (now + timedelta(days=1)).replace(hour=3, minute=0, second=0, microsecond=0)
    did = f"hb-dream-{dream_at.strftime('%Y-%m-%d')}"
    if did not in ids:
        items.append({"id": did, "at": dream_at.isoformat(), "devin": DREAM})
        added += 1

    if added:
        json.dump(items, open(REM, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    os.makedirs(os.path.dirname(STATE), exist_ok=True)
    json.dump({"date": today, "made": True, "added": added},
              open(STATE, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"heartbeats added: {added}")

    if not added:
        return 0
    for cmd in (["git", "pull", "--rebase"], ["git", "add", "reminders.json"],
                ["git", "-c", "user.name=Devin",
                 "-c", "user.email=158243242+devin-ai-integration[bot]@users.noreply.github.com",
                 "commit", "-m", f"heartbeat: {today} free turns", "-m", "Generated by heartbeat.py"],
                ["git", "push"]):
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        if r.returncode != 0 and "nothing to commit" not in (r.stdout + r.stderr):
            print(f"git fail {cmd[1]}: {r.stderr[:300]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
